export interface HeroDef {
  id: string;
  name: string;
  /** Роль для фильтра на экране выбора */
  roleId: RoleId;
  /** Подпись роли на карточке */
  role: string;
  /** Одна строка о стиле игры */
  tagline: string;
  /** Винительный падеж для сообщений («убил вашего мага») */
  acc: string;
  /** Женский род («повержена», «вернулась») */
  fem?: boolean;
  ranged: boolean;
  baseHp: number;
  hpLvl: number;
  baseDmg: number;
  dmgLvl: number;
  baseSpeed: number;
  range: number;
  /** Секунд между атаками */
  atkInt: number;
  radius: number;
  barH: number;
  armor: number;
  /** Способности по слотам Q W E R (R — ультимейт, открывается на 6 уровне) */
  abilities: string[];
  /** Закупка бота по порядку */
  /** Рекомендуемые предметы по порядку: их показывает лавка и по ним закупается бот */
  build: string[];
  /** Цвет героя в интерфейсе */
  color: string;
}

